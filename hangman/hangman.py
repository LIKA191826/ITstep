# Hangman - სიტყვის გამოცნობის თამაში
# ეს პროგრამა ირჩევს შემთხვევით სიტყვას და მოთამაშე ასოებით უნდა გამოიცნოს

import random  # შემთხვევითი სიტყვის ასარჩევად გვჭირდება

# სიტყვების სია, საიდანაც კომპიუტერი ერთს შემთხვევით აირჩევს
words = ["python", "computer", "program", "keyboard", "mouse", "hangman", "student"]

# თამაშის დაწყებისას შემთხვევით ვირჩევთ ერთ სიტყვას სიიდან
secret_word = random.choice(words)

# აქ ვინახავთ იმ ასოებს, რომლებიც მოთამაშემ უკვე სცადა
guessed_letters = []

# რამდენი არასწორი მცდელობა დარჩა (ჩვეულებრივ ჰანგმენში 6 ცდაა)
tries = 6

# ეს ფუნქცია ხატავს ჰანგმენს იმის მიხედვით, რამდენი ცდა დარჩა
def draw_hangman(tries_left):
    # ყოველი არასწორი პასუხის შემდეგ ფიგურა უფრო მეტად იხატება
    stages = [
        """
           ------
           |    |
           |    O
           |   /|\\
           |   / \\
           |
        """,
        """
           ------
           |    |
           |    O
           |   /|\\
           |   /
           |
        """,
        """
           ------
           |    |
           |    O
           |   /|\\
           |
           |
        """,
        """
           ------
           |    |
           |    O
           |   /|
           |
           |
        """,
        """
           ------
           |    |
           |    O
           |    |
           |
           |
        """,
        """
           ------
           |    |
           |    O
           |
           |
           |
        """,
        """
           ------
           |    |
           |
           |
           |
           |
        """
    ]
    # stages[0] = სრულად დახატული (0 ცდა), stages[6] = მხოლოდ ჩარჩო (6 ცდა)
    print(stages[tries_left])


# ეს ფუნქცია აჩვენებს სიტყვას ასოებით ან ტირეებით
# მაგალითად: თუ სიტყვაა python და გამოცნობილია p და o -> p _ _ _ o _
def show_word():
    result = ""
    for letter in secret_word:
        if letter in guessed_letters:
            # თუ ასო უკვე გამოცნობილია, ვაჩვენებთ მას
            result = result + letter + " "
        else:
            # თუ ჯერ არ არის გამოცნობილი, ვაჩვენებთ ტირეს
            result = result + "_ "
    print(result)


# თამაშის მისალმება
print("მოგესალმებით Hangman-ში!")
print("გამოიცანი სიტყვა ასოების გამოცნობით.")
print("გაქვს 6 მცდელობა.\n")

# თამაში გრძელდება სანამ ცდები არ ამოიწურება ან სიტყვა არ გამოიცნობა
while tries > 0:
    # ვხატავთ ჰანგმენს და ვაჩვენებთ სიტყვის მიმდინარე მდგომარეობას
    draw_hangman(tries)
    show_word()
    print("დარჩენილი ცდები:", tries)
    print("უკვე ნაცადი ასოები:", guessed_letters)

    # მოთამაშისგან ვითხოვთ ერთ ასოს
    guess = input("შეიყვანე ერთი ასო: ").lower()

    # ვამოწმებთ, რომ შეყვანილია მხოლოდ ერთი ასო და რომ ის არის ანბანის ასო
    if len(guess) != 1 or not guess.isalpha():
        print("გთხოვ, შეიყვანე მხოლოდ ერთი ასო!\n")
        continue  # თავიდან ვიწყებთ ციკლს, ცდა არ იკლებს

    # თუ ეს ასო უკვე იყო ნაცადი, კიდევ ერთხელ არ ვითვლით
    if guess in guessed_letters:
        print("ეს ასო უკვე სცადე!\n")
        continue

    # ახალ ასოს ვამატებთ ნაცად ასოების სიაში
    guessed_letters.append(guess)

    # ვამოწმებთ, არის თუ არა ეს ასო საიდუმლო სიტყვაში
    if guess in secret_word:
        print("სწორია! ასო არის სიტყვაში.\n")
    else:
        # თუ ასო არ არის სიტყვაში, ერთი ცდა იკლებს
        tries = tries - 1
        print("არასწორია! ასო არ არის სიტყვაში.\n")

    # ვამოწმებთ, გამოიცნო თუ არა მოთამაშემ მთელი სიტყვა
    # თუ სიტყვის ყველა ასო უკვე არის guessed_letters-ში, მოთამაშემ მოიგო
    won = True
    for letter in secret_word:
        if letter not in guessed_letters:
            won = False
            break

    if won:
        draw_hangman(tries)
        show_word()
        print("გილოცავ! შენ გამოიცანი სიტყვა:", secret_word)
        break  # თამაში მთავრდება, რადგან მოვიგეთ

# თუ ციკლი დასრულდა და ცდები ამოიწურა, მოთამაშემ წააგო
if tries == 0:
    draw_hangman(tries)
    print("სამწუხაროდ წააგე.")
    print("სწორი სიტყვა იყო:", secret_word)
