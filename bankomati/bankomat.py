# ============================================================
# მარტივი ბანკომატი (ATM)
# ეს პროგრამა იმიტირებს ბანკომატის მუშაობას:
# პინის შემოწმება, ბალანსის ნახვა, ფულის გამოტანა და შეტანა
# ============================================================

# საწყისი ბალანსი ანგარიშზე (ლარი)
balansi = 1000

# სწორი პინ კოდი
sori_pini = "1234"

# რამდენჯერ შეუძლია მომხმარებელს არასწორი პინის შეყვანა
max_cdeba = 3


# ------------------------------------------------------------
# ფუნქცია: პინის შემოწმება
# მომხმარებელს აქვს 3 ცდა. თუ ყველა არასწორია — პროგრამა იხურება
# ------------------------------------------------------------
def pini_shemtsomeba():
    cdeba = 0  # რამდენი ცდა უკვე გამოყენებულია

    while cdeba < max_cdeba:
        # input() აბრუნებს ტექსტს, ამიტომ პინსაც სტრინგად ვადარებთ
        sheyvanili_pini = input("შეიყვანეთ პინ კოდი: ")

        if sheyvanili_pini == sori_pini:
            print("პინი სწორია. მოგესალმებით!\n")
            return True  # პინი სწორია — ვაბრუნებთ True-ს
        else:
            cdeba = cdeba + 1
            darchenili = max_cdeba - cdeba
            print("პინი არასწორია!")
            if darchenili > 0:
                print("დარჩენილი ცდები:", darchenili)

    # თუ აქამდე მოვედით, ყველა ცდა ამოიწურა
    print("ბარათი დაბლოკილია. სცადეთ მოგვიანებით.")
    return False


# ------------------------------------------------------------
# ფუნქცია: ბალანსის ჩვენება
# ------------------------------------------------------------
def balansi_chveneba():
    print("თქვენი ბალანსია:", balansi, "ლარი")


# ------------------------------------------------------------
# ფუნქცია: ფულის გამოტანა
# ვამოწმებთ რომ თანხა დადებითი იყოს და ბალანსზე საკმარისი იყოს
# ------------------------------------------------------------
def fulis_gamotana():
    global balansi  # global - რომ შეგვიძლია შევცვალოთ გარე ცვლადი balansi

    tanxa = input("რამდენი ლარის გამოტანა გსურთ? ")

    # ვამოწმებთ რომ მომხმარებელმა რიცხვი შეიყვანა და არა ტექსტი
    if tanxa.isdigit() == False:
        print("გთხოვთ შეიყვანოთ მხოლოდ რიცხვი.")
        return

    tanxa = int(tanxa)  # სტრინგს ვაქცევთ მთელ რიცხვად

    if tanxa <= 0:
        print("შეიყვანეთ 0-ზე მეტი თანხა.")
    elif tanxa > balansi:
        print("არასაკმარისი თანხა ანგარიშზე.")
        print("თქვენი ბალანსია:", balansi, "ლარი")
    else:
        balansi = balansi - tanxa
        print("გამოიტანეთ", tanxa, "ლარი.")
        print("ახალი ბალანსია:", balansi, "ლარი")


# ------------------------------------------------------------
# ფუნქცია: ფულის შეტანა
# ------------------------------------------------------------
def fulis_shetana():
    global balansi

    tanxa = input("რამდენი ლარის შეტანა გსურთ? ")

    if tanxa.isdigit() == False:
        print("გთხოვთ შეიყვანოთ მხოლოდ რიცხვი.")
        return

    tanxa = int(tanxa)

    if tanxa <= 0:
        print("შეიყვანეთ 0-ზე მეტი თანხა.")
    else:
        balansi = balansi + tanxa
        print("შეიტანეთ", tanxa, "ლარი.")
        print("ახალი ბალანსია:", balansi, "ლარი")


# ------------------------------------------------------------
# ფუნქცია: მთავარი მენიუ
# მომხმარებელი ირჩევს ოპერაციას სანამ არ გავა
# ------------------------------------------------------------
def mtavari_menu():
    while True:
        print("========== ბანკომატი ==========")
        print("1. ბალანსის ნახვა")
        print("2. ფულის გამოტანა")
        print("3. ფულის შეტანა")
        print("4. გასვლა")
        print("===============================")

        archevani = input("აირჩიეთ ოპერაცია (1-4): ")

        if archevani == "1":
            balansi_chveneba()
        elif archevani == "2":
            fulis_gamotana()
        elif archevani == "3":
            fulis_shetana()
        elif archevani == "4":
            print("გმადლობთ რომ ისარგებლეთ ჩვენი ბანკომატით. ნახვამდის!")
            break  # ვწყვეტთ ციკლს და ვასრულებთ პროგრამას
        else:
            print("არასწორი არჩევანი. გთხოვთ აირჩიოთ 1-დან 4-მდე.")

        print()  # ცარიელი ხაზი რომ მენიუ უფრო მოხერხებულად ჩანდეს


# ------------------------------------------------------------
# პროგრამის დაწყება
# ჯერ ვამოწმებთ პინს, თუ სწორია — ვაჩვენებთ მენიუს
# ------------------------------------------------------------
print("კეთილი იყოს თქვენი მობრძანება ბანკომატში!")

if pini_shemtsomeba() == True:
    mtavari_menu()
